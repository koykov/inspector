func TestNewCompilerNilConfig(t *testing.T) {
	c, err := NewCompiler(nil)
	require.Nil(t, c)
	require.ErrorIs(t, err, ErrNoConfig)
}

func TestCompileZeroCompiler(t *testing.T) {
	require.ErrorIs(t, (&Compiler{}).Compile(), ErrNoConfig)
}

const fixtureSrc = `package fixture

type Simple struct {
	Name   string
	Data   []byte
	Count  int32
	Score  float64
	OK     bool
	Items  []int32
	Tags   map[string]int32
	Child  *Child
	Nested Child
}

type Child struct {
	Title string
}
`

func newFixtureCompiler(t *testing.T, buf *bytes.Buffer) *Compiler {
	t.Helper()
	old := tmpCntr
	t.Cleanup(func() { tmpCntr = old })
	c, err := NewCompiler(&Config{
		Target: TargetFile,
		File:   "fixture.go",
		Import: "example.com/fixture",
		Buf:    buf,
	})
	require.NoError(t, err)
	c.pkg = c.imp_
	return c
}

func parseFixture(t *testing.T, c *Compiler, src string) {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "fixture.go", src, parser.ParseComments)
	require.NoError(t, err)
	require.NoError(t, c.parseAstFile(f))
}

func TestCompilerGenerateInMemory(t *testing.T) {
	var buf bytes.Buffer
	c := newFixtureCompiler(t, &buf)
	parseFixture(t, c, fixtureSrc)
	require.Len(t, c.nodes, 2)

	for _, n := range c.nodes {
		buf.Reset()
		require.NoError(t, c.writeType(n))
		src := buf.String()

		_, err := format.Source([]byte(src))
		require.NoError(t, err, "generated source must be valid Go")

		_, err = parser.ParseFile(token.NewFileSet(), "generated.go", src, 0)
		require.NoError(t, err, "generated source must parse as Go")

		require.Contains(t, src, "// Code generated by inspc. DO NOT EDIT.")
		require.Contains(t, src, "// source: example.com/fixture")
		require.Contains(t, src, "package fixture_ins")
		require.Contains(t, src, `"github.com/koykov/inspector"`)
		require.Contains(t, src, `"example.com/fixture"`)
		require.Contains(t, src, "func init() {")
		require.Contains(t, src, "inspector.RegisterInspector(")

		for _, sig := range []string{
			") TypeName(", ") Instance(", ") Get(", ") GetTo(", ") Set(", ") SetWithBuffer(",
			") Compare(", ") Loop(", ") DeepEqual(", ") DeepEqualWithOptions(", ") Unmarshal(",
			") Copy(", ") CopyTo(", ") Append(", ") Length(", ") Capacity(", ") Each(", ") Reset(",
		} {
			require.Contains(t, src, sig)
		}
	}
	require.Equal(t, 2, c.GetTotal())
}

func TestCompilerGenerateSimpleContent(t *testing.T) {
	var buf bytes.Buffer
	c := newFixtureCompiler(t, &buf)
	parseFixture(t, c, fixtureSrc)
	for _, n := range c.nodes {
		if n.name != "Simple" {
			continue
		}
		buf.Reset()
		require.NoError(t, c.writeType(n))
		src := buf.String()
		require.Contains(t, src, "strconv.ParseInt")
		require.Contains(t, src, "strconv.ParseFloat")
		require.Contains(t, src, "strconv.ParseBool")
		return
	}
	t.Fatal("Simple node not found")
}

func TestParseAstExprUnsupported(t *testing.T) {
	var buf bytes.Buffer
	c := newFixtureCompiler(t, &buf)
	_, err := c.parseAstExpr(&ast.ChanType{Dir: ast.SEND, Value: ast.NewIdent("int")}, nil, 0)
	require.ErrorIs(t, err, ErrUnsupportedType)
}

func TestUnknownTarget(t *testing.T) {
	c, err := NewCompiler(&Config{Target: Target(99)})
	require.Nil(t, c)
	require.ErrorIs(t, err, ErrUnknownTarget)
}
